-- Persistent, append-only QA repair telemetry.
-- Records repair attempts, selected replacement assets and the final post-render QA outcome.
-- No browser role receives privileges; the server uses the Supabase service-role key only.

create table if not exists public.short_qa_repair_events (
  id bigint generated by default as identity primary key,
  repair_id uuid not null,
  job_id text not null,
  attempt smallint not null check (attempt > 0),
  event_type text not null check (event_type in (
    'repair_started',
    'asset_selected',
    'repair_succeeded',
    'repair_failed',
    'repair_cancelled'
  )),
  scene_index integer check (scene_index is null or scene_index >= 0),
  provider text check (provider is null or provider in ('pexels', 'pixabay')),
  provider_asset_id text,
  canonical_asset_id text,
  cause_code text,
  reason text,
  action text,
  outcome text,
  qa_before jsonb not null default '{}'::jsonb,
  qa_after jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists short_qa_repair_events_job_idx
  on public.short_qa_repair_events (job_id, occurred_at desc);
create index if not exists short_qa_repair_events_repair_idx
  on public.short_qa_repair_events (repair_id, occurred_at asc);
create index if not exists short_qa_repair_events_type_idx
  on public.short_qa_repair_events (event_type, occurred_at desc);
create index if not exists short_qa_repair_events_asset_idx
  on public.short_qa_repair_events (provider, provider_asset_id)
  where provider_asset_id is not null;

-- Append-only history: public/authenticated clients cannot access it and the
-- server can insert/read but cannot rewrite or delete historical outcomes.
alter table public.short_qa_repair_events enable row level security;
revoke all on table public.short_qa_repair_events from anon, authenticated, service_role;
grant select, insert on table public.short_qa_repair_events to service_role;
revoke all on sequence public.short_qa_repair_events_id_seq from anon, authenticated, service_role;
grant usage, select on sequence public.short_qa_repair_events_id_seq to service_role;
