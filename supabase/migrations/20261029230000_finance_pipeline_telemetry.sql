-- Finance Short Pipeline v2 telemetry and feedback loop.
-- Apply after the existing short history migrations.

create table if not exists public.short_pipeline_runs (
  id text primary key,
  job_id text,
  plan_id text not null,
  source text not null default 'finance-v2',
  status text not null check (status in ('planned','queued','rendering','completed','failed','cancelled')),
  title text not null,
  article_url text,
  niche text,
  hook_text text not null,
  cta_text text,
  selected_hook_variant text,
  facts jsonb not null default '[]'::jsonb,
  plan jsonb not null default '{}'::jsonb,
  quality_gate jsonb not null default '{}'::jsonb,
  architecture jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists short_pipeline_runs_niche_idx on public.short_pipeline_runs (niche);
create index if not exists short_pipeline_runs_status_idx on public.short_pipeline_runs (status);
create index if not exists short_pipeline_runs_created_idx on public.short_pipeline_runs (created_at desc);

create table if not exists public.short_pipeline_hook_variants (
  run_id text not null references public.short_pipeline_runs(id) on delete cascade,
  variant_key text not null,
  hook_text text not null,
  selected boolean not null default false,
  generated_score numeric,
  created_at timestamptz not null default now(),
  primary key (run_id, variant_key)
);

create index if not exists short_pipeline_hook_variants_hook_idx on public.short_pipeline_hook_variants (hook_text);

create table if not exists public.short_pipeline_events (
  id bigint generated by default as identity primary key,
  run_id text not null references public.short_pipeline_runs(id) on delete cascade,
  job_id text,
  event_type text not null,
  scene_index integer,
  payload jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists short_pipeline_events_run_idx on public.short_pipeline_events (run_id, occurred_at desc);
create index if not exists short_pipeline_events_type_idx on public.short_pipeline_events (event_type, occurred_at desc);

create table if not exists public.short_retention_metrics (
  id bigint generated by default as identity primary key,
  run_id text references public.short_pipeline_runs(id) on delete set null,
  job_id text,
  platform text not null,
  external_video_id text,
  hook_text text,
  niche text,
  views bigint,
  average_watch_seconds numeric,
  average_completion_rate numeric,
  retention_1s numeric,
  retention_3s numeric,
  retention_50_percent numeric,
  retention_100_percent numeric,
  likes bigint,
  comments bigint,
  shares bigint,
  saves bigint,
  captured_at timestamptz not null default now(),
  raw jsonb not null default '{}'::jsonb
);

create index if not exists short_retention_metrics_niche_idx on public.short_retention_metrics (niche, captured_at desc);
create index if not exists short_retention_metrics_hook_idx on public.short_retention_metrics (hook_text);
create unique index if not exists short_retention_metrics_external_idx on public.short_retention_metrics (platform, external_video_id) where external_video_id is not null;

create or replace view public.pipeline_learning_signals as
select
  niche,
  hook_text,
  count(*)::bigint as sample_size,
  avg(average_completion_rate)::numeric as average_completion_rate,
  avg(average_watch_seconds)::numeric as average_watch_seconds,
  avg(coalesce(shares, 0))::numeric as average_shares
from public.short_retention_metrics
where hook_text is not null and trim(hook_text) <> ''
group by niche, hook_text
having count(*) >= 1;

alter table public.short_pipeline_runs enable row level security;
alter table public.short_pipeline_events enable row level security;
alter table public.short_retention_metrics enable row level security;

